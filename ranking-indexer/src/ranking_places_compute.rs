//! The Rust twin of the Best debates ranking places and push-downs (migration 0124, GEO-3681).
//!
//! 0124 lets the top of Best follow the Debates space's Best debates ranking instead of agendas, behind
//! `entity_ranking_config.ranking_places_mode` (0 off, the default; 1 shadow; 2 on). The hourly sweep keeps two
//! small tables, `trending.ranking_places` and `trending.ranking_pushdowns`, from `ranks.*` and `user_votes`, and
//! `trending.entity_trending_terms` turns them into a place value inside the GREATEST and a flat push-down after
//! it. This module is the logic of those reads; the term arithmetic is
//! [`crate::entity_ranking_score_compute::trending_terms`] and the target set and re-score ids are in
//! [`crate::agenda_rescore_compute`].
//!
//! | Rust | SQL (0124) |
//! | -- | -- |
//! | [`member_ballots`] | `trending.ranking_member_ballots` (with `trending.ranking_members`) |
//! | [`pushdowns`] | `trending.current_ranking_pushdowns` |
//! | [`places`] | `trending.current_ranking_places` |
//! | [`place_values`] | `trending.ranking_place_values` |
//! | [`ranked_ids`] | the `ranked_ids` of `trending.refresh_agenda_listings` |
//!
//! `trending.rankable_debates` (typed Debate, present in `entities`, not on `entity_feed_blocklist`) is a set the
//! caller builds: [`Rankable`].
//!
//! Pinned to the SQL by `tests/fixtures/ranking_places_golden.txt`, generated by
//! `api/scripts/rankingplaces/gen_golden.py` from the migrations' own function bodies on a scratch Postgres.
//! Nothing here writes anything.

use std::collections::{BTreeMap, BTreeSet, HashMap, HashSet};

use chrono::{DateTime, NaiveDate, Utc};
use uuid::Uuid;

use crate::sql_helpers::calendar_day;

/// A row of `trending.ranking_place_sources`.
#[derive(Debug, Clone, PartialEq)]
pub struct Source {
    pub name: String,
    pub space_id: Uuid,
    pub block_id: Uuid,
    pub weight: f64,
    pub window_days: Option<i32>,
    pub slots: i32,
    pub day_factor: f64,
}

/// A row of `ranks.rankings`: one submitted ballot.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Ballot {
    pub id: Uuid,
    pub block_id: Option<Uuid>,
    pub space_id: Uuid,
    pub updated_at_block: i64,
    pub update_index: i64,
}

/// A row of `user_votes`. `voted_at_us` is microseconds since the epoch.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Vote {
    pub user_id: Uuid,
    pub object_id: Uuid,
    pub object_type: i16,
    pub vote_kind: i16,
    pub vote_type: i16,
    pub voted_at_us: i64,
}

/// What the reads see of `ranks.*` and `user_votes`.
#[derive(Debug, Clone, Default)]
pub struct Ranks {
    /// `ranks.ranking_scores` as `(block_id, entity_id, position)` (the item space is not read).
    pub scores: Vec<(Uuid, Uuid, i32)>,
    pub ballots: Vec<Ballot>,
    /// `ranks.ranking_items` as `(ranking_id, entity_id, rank_space_id)`: an
    /// item belongs to the ballot `(ranking_id, rank_space_id)` (GEO-3591, 0125).
    pub items: Vec<(Uuid, Uuid, Uuid)>,
    /// `ranks.members` ∪ `ranks.editors` as `(member_space_id, space_id)`.
    pub members: Vec<(Uuid, Uuid)>,
    pub votes: Vec<Vote>,
}

/// `trending.rankable_debates`: the Debate-typed entities present in `entities` and not blocklisted, with their
/// created epoch (`None` unless `created_at` is all digits).
pub type Rankable = HashMap<Uuid, Option<i64>>;

/// A row of `trending.ranking_places`.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct Place {
    pub source: String,
    pub entity_id: Uuid,
    pub place: i32,
}

/// `trending.epoch_day`: the New York calendar day of an epoch.
pub fn epoch_day(epoch: i64) -> Option<NaiveDate> {
    DateTime::<Utc>::from_timestamp(epoch, 0).map(calendar_day)
}

/// `trending.ranking_members`: `(space, block, member)` for each source's (space, block).
fn members(sources: &[Source], ranks: &Ranks) -> BTreeSet<(Uuid, Uuid, Uuid)> {
    let pairs: BTreeSet<(Uuid, Uuid)> = sources.iter().map(|s| (s.space_id, s.block_id)).collect();
    let mut out = BTreeSet::new();
    for (space, block) in &pairs {
        for (member, of) in &ranks.members {
            if of == space {
                out.insert((*space, *block, *member));
            }
        }
    }
    out
}

/// `trending.ranking_member_ballots`: `(space, block, member, entity)` for every item on each member's latest
/// ballot on a source block (`updated_at_block` DESC, `update_index` DESC, then the lower id).
pub fn member_ballots(sources: &[Source], ranks: &Ranks) -> BTreeSet<(Uuid, Uuid, Uuid, Uuid)> {
    let blocks: HashSet<Uuid> = sources.iter().map(|s| s.block_id).collect();
    let mut latest: BTreeMap<(Uuid, Uuid), Ballot> = BTreeMap::new();
    for b in &ranks.ballots {
        let Some(block) = b.block_id.filter(|k| blocks.contains(k)) else {
            continue;
        };
        let better = |cur: &Ballot| {
            (b.updated_at_block, b.update_index, std::cmp::Reverse(b.id))
                > (
                    cur.updated_at_block,
                    cur.update_index,
                    std::cmp::Reverse(cur.id),
                )
        };
        match latest.get(&(block, b.space_id)) {
            Some(cur) if !better(cur) => {}
            _ => {
                latest.insert((block, b.space_id), *b);
            }
        }
    }
    let m = members(sources, ranks);
    let mut items: HashMap<(Uuid, Uuid), Vec<Uuid>> = HashMap::new();
    for (ranking, entity, rank_space) in &ranks.items {
        items
            .entry((*ranking, *rank_space))
            .or_default()
            .push(*entity);
    }
    let mut out = BTreeSet::new();
    for ((block, member), ballot) in &latest {
        for (space, b, mem) in &m {
            if b == block && mem == member {
                for entity in items
                    .get(&(ballot.id, ballot.space_id))
                    .into_iter()
                    .flatten()
                {
                    out.insert((*space, *block, *member, *entity));
                }
            }
        }
    }
    out
}

/// `trending.current_ranking_pushdowns`: per pushed-down debate, `(downvoters, rankers)`. `since` is
/// `ranking_pushdown_since` (epoch seconds; 0 counts nothing).
pub fn pushdowns(
    sources: &[Source],
    ranks: &Ranks,
    rankable: &Rankable,
    since: i64,
) -> BTreeMap<Uuid, (i32, i32)> {
    let m = members(sources, ranks);
    // (space, block, entity) -> distinct downvoters
    let mut down: BTreeMap<(Uuid, Uuid, Uuid), BTreeSet<Uuid>> = BTreeMap::new();
    if since > 0 {
        for v in &ranks.votes {
            if v.object_type != 0
                || v.vote_kind != 0
                || v.vote_type != 1
                || v.voted_at_us < since * 1_000_000
            {
                continue;
            }
            for (space, block, member) in &m {
                if *member == v.user_id {
                    down.entry((*space, *block, v.object_id))
                        .or_default()
                        .insert(v.user_id);
                }
            }
        }
    }
    let mut ranked: HashMap<(Uuid, Uuid, Uuid), BTreeSet<Uuid>> = HashMap::new();
    for (space, block, member, entity) in member_ballots(sources, ranks) {
        ranked
            .entry((space, block, entity))
            .or_default()
            .insert(member);
    }
    // DISTINCT ON (entity) ORDER BY margin DESC, downvoters DESC, space, block.
    let mut best: BTreeMap<Uuid, (i32, i32, Uuid, Uuid)> = BTreeMap::new();
    for ((space, block, entity), voters) in &down {
        if !rankable.contains_key(entity) {
            continue;
        }
        let d = voters.len() as i32;
        let r = ranked
            .get(&(*space, *block, *entity))
            .map_or(0, |s| s.len() as i32);
        if d <= r {
            continue;
        }
        let key = |x: &(i32, i32, Uuid, Uuid)| {
            (
                std::cmp::Reverse(x.0 - x.1),
                std::cmp::Reverse(x.0),
                x.2,
                x.3,
            )
        };
        let cand = (d, r, *space, *block);
        match best.get(entity) {
            Some(cur) if key(cur) <= key(&cand) => {}
            _ => {
                best.insert(*entity, cand);
            }
        }
    }
    best.into_iter()
        .map(|(e, (d, r, _, _))| (e, (d, r)))
        .collect()
}

/// `trending.current_ranking_places`: each source's block ranking deduped by entity (its best position), rankable
/// and not pushed down, inside the window, renumbered 1.. by position then entity id, cut at the slots.
pub fn places(
    sources: &[Source],
    ranks: &Ranks,
    rankable: &Rankable,
    pushed: &BTreeSet<Uuid>,
    today: NaiveDate,
) -> BTreeSet<Place> {
    let mut out = BTreeSet::new();
    for s in sources {
        let mut best: BTreeMap<Uuid, i32> = BTreeMap::new();
        for (block, entity, position) in &ranks.scores {
            if *block == s.block_id {
                let e = best.entry(*entity).or_insert(*position);
                *e = (*e).min(*position);
            }
        }
        let mut rows: Vec<(i32, Uuid)> = best
            .into_iter()
            .filter(|(entity, _)| !pushed.contains(entity))
            .filter_map(|(entity, position)| {
                let created = rankable.get(&entity)?;
                let created_on = created.and_then(epoch_day);
                let inside = match s.window_days {
                    None => true,
                    Some(w) => created_on.is_some_and(|d| (today - d).num_days() < i64::from(w)),
                };
                inside.then_some((position, entity))
            })
            .collect();
        rows.sort();
        for (i, (_, entity)) in rows.into_iter().enumerate() {
            let place = i as i32 + 1;
            if place > s.slots {
                break;
            }
            out.insert(Place {
                source: s.name.clone(),
                entity_id: entity,
                place,
            });
        }
    }
    out
}

/// `trending.ranking_place_values`: per placed entity in `ids` with a numeric created time, its best weighted
/// place value `weight × (base + step × (slots − place + 1)) × day_factor^age_days`.
pub fn place_values(
    base: f64,
    step: f64,
    sources: &[Source],
    places: &BTreeSet<Place>,
    created: &HashMap<Uuid, Option<i64>>,
    ids: &HashSet<Uuid>,
    today: NaiveDate,
) -> HashMap<Uuid, f64> {
    let by_name: HashMap<&str, &Source> = sources.iter().map(|s| (s.name.as_str(), s)).collect();
    let mut out: HashMap<Uuid, f64> = HashMap::new();
    for p in places {
        if !ids.contains(&p.entity_id) {
            continue;
        }
        let Some(s) = by_name.get(p.source.as_str()) else {
            continue;
        };
        if p.place > s.slots {
            continue;
        }
        let Some(Some(epoch)) = created.get(&p.entity_id) else {
            continue;
        };
        let Some(day) = epoch_day(*epoch) else {
            continue;
        };
        let age = (today - day).num_days().max(0);
        let v = place_value(base, step, s.weight, s.slots, p.place, s.day_factor, age);
        let e = out.entry(p.entity_id).or_insert(v);
        *e = e.max(v);
    }
    out
}

/// One source's value at `place` for a debate `age_days` old.
pub fn place_value(
    base: f64,
    step: f64,
    weight: f64,
    slots: i32,
    place: i32,
    day_factor: f64,
    age_days: i64,
) -> f64 {
    weight * (base + step * f64::from(slots - place + 1)) * day_factor.powi(age_days as i32)
}

/// The ranking's share of the ids `trending.refresh_agenda_listings` re-scores: while on (mode 2), every debate
/// whose place row or push-down came, went or changed; on a full pass (any mode), every debate in either table
/// before or after.
pub fn ranked_ids(
    mode: i32,
    full_pass: bool,
    stored_places: &BTreeSet<Place>,
    incoming_places: &BTreeSet<Place>,
    stored_pushdowns: &BTreeSet<Uuid>,
    incoming_pushdowns: &BTreeSet<Uuid>,
) -> BTreeSet<Uuid> {
    let mut ids = BTreeSet::new();
    if mode == 2 {
        ids.extend(
            stored_places
                .symmetric_difference(incoming_places)
                .map(|p| p.entity_id),
        );
        ids.extend(stored_pushdowns.symmetric_difference(incoming_pushdowns));
    }
    if full_pass {
        ids.extend(
            stored_places
                .iter()
                .chain(incoming_places)
                .map(|p| p.entity_id),
        );
        ids.extend(stored_pushdowns.iter().chain(incoming_pushdowns));
    }
    ids
}

