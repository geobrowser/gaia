    /// The three cases GEO-3681 names, as the SQL scored them in `on_full`.
    #[test]
    fn the_named_cases() {
        let f = load();
        let s = &f.scenarios.iter().find(|(n, _)| n == "on_full").unwrap().1;
        let term = |k: &str| {
            let e = f.cases[k];
            s.want_terms.iter().find(|t| t.0 == e).unwrap().2
        };
        let places_of = |k: &str| {
            s.want_places
                .iter()
                .filter(|p| p.entity_id == f.cases[k])
                .count()
        };
        let listed = |k: &str| f.listings.iter().any(|l| l.entity_id == f.cases[k]);
        // Ranked, never listed: a place.
        assert!(
            !listed("ranked_not_listed")
                && places_of("ranked_not_listed") == 1
                && term("ranked_not_listed") > 500.0
        );
        // In both rows: the larger weighted value, not the sum.
        assert_eq!(places_of("in_both"), 2);
        let v = s
            .want_values
            .iter()
            .find(|v| v.0 == f.cases["in_both"])
            .unwrap()
            .1;
        assert!(close(term("in_both"), v) && v > 1000.0);
        // Pushed down: no place, a flat −100 after the GREATEST, also on a listed debate.
        assert_eq!(places_of("pushed"), 0);
        assert!(close(term("pushed"), -s.pushdown));
        assert!(listed("pushed_listed") && close(term("pushed_listed"), f.cfg[1] - s.pushdown));
        // ...and no age credit, which an agenda listing would otherwise add back.
        let age = s
            .want_terms
            .iter()
            .find(|t| t.0 == f.cases["pushed_listed"])
            .unwrap()
            .1;
        assert_eq!(age, 0.0);
    }

